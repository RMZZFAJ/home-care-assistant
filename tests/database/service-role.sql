-- Local regression only. Fixtures and temporary privilege probes roll back.
begin;
create or replace function pg_temp.assert_ok(p_ok boolean,p_message text) returns void language plpgsql as $$begin
  if not coalesce(p_ok,false) then raise exception 'ASSERTION FAILED: %',p_message;end if;
end;$$;
create or replace function pg_temp.must_fail(p_sql text,p_message text) returns void language plpgsql as $$declare caught boolean:=false;begin
  begin execute p_sql;exception when insufficient_privilege then caught:=true;end;
  perform pg_temp.assert_ok(caught,p_message);
end;$$;

grant execute on function pg_temp.assert_ok(boolean,text),pg_temp.must_fail(text,text) to authenticated,service_role;

select pg_temp.assert_ok(not exists(select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind in ('r','v') and
  (has_table_privilege('service_role',c.oid,'SELECT') or has_table_privilege('service_role',c.oid,'INSERT')
   or has_table_privilege('service_role',c.oid,'UPDATE') or has_table_privilege('service_role',c.oid,'DELETE')
   or has_table_privilege('service_role',c.oid,'TRUNCATE'))),'service role has no direct table privileges');
select pg_temp.assert_ok(not exists(select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind='S' and
  (has_sequence_privilege('service_role',c.oid,'USAGE') or has_sequence_privilege('service_role',c.oid,'UPDATE')
   or has_sequence_privilege('service_role',c.oid,'SELECT'))),'service role cannot manufacture sequence values');
select pg_temp.assert_ok(not exists(select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where n.nspname='public' and not exists(select 1 from pg_depend d where d.classid='pg_proc'::regclass and d.objid=p.oid and d.deptype='e')
    and has_function_privilege('service_role',p.oid,'EXECUTE')
    and p.proname not in ('claim_notification_jobs','validate_notification_job','complete_notification_job','notification_webhook','notification_job_state')),
  'service role executes only the worker application functions');

create table public.hca_service_privilege_probe(id bigint generated by default as identity);
create function public.hca_service_privilege_probe() returns boolean language sql as $$select true$$;
select pg_temp.assert_ok(not has_table_privilege('service_role','public.hca_service_privilege_probe','SELECT,INSERT,UPDATE,DELETE,TRUNCATE'), 'future table defaults do not reopen privileges');
select pg_temp.assert_ok(not has_sequence_privilege('service_role','public.hca_service_privilege_probe_id_seq','USAGE,SELECT,UPDATE'), 'future sequence defaults do not reopen privileges');
select pg_temp.assert_ok(not has_function_privilege('service_role','public.hca_service_privilege_probe()','EXECUTE'), 'future function defaults do not reopen privileges');
select pg_temp.assert_ok(not has_function_privilege('anon','public.hca_service_privilege_probe()','EXECUTE')
  and not has_function_privilege('authenticated','public.hca_service_privilege_probe()','EXECUTE'),
  'global PUBLIC defaults cannot reopen future function access');

select set_config('request.jwt.claim.role','service_role',true);
select set_config('request.jwt.claim.sub','',true);
set local role service_role;
select pg_temp.must_fail('select state from public.requisition_notifications','service role cannot read the private outbox');
select pg_temp.must_fail('truncate public.requisition_notifications','service role cannot truncate the private outbox');
select pg_temp.assert_ok(public.notification_job_state('10000000-0000-4000-8000-000000000099') is null,'authorized missing state is safely null');
reset role;
select set_config('request.jwt.claim.role','authenticated',true);
select set_config('request.jwt.claim.sub',(select id::text from public.profiles where full_name='Teste adminA'),true);
set local role authenticated;
select pg_temp.must_fail($q$select public.notification_job_state('10000000-0000-4000-8000-000000000099')$q$,'patient administrator cannot use worker state lookup');
reset role;
select set_config('request.jwt.claim.sub',(select id::text from public.profiles where full_name='Teste global'),true);
set local role authenticated;
select pg_temp.assert_ok(public.notification_job_state('10000000-0000-4000-8000-000000000099') is null,'global administrator can reconcile its worker result');
reset role;
select pg_temp.assert_ok(not has_function_privilege('anon','public.notification_job_state(uuid)','EXECUTE'),'anonymous state lookup denied');
select 'service role privilege regressions passed';
rollback;
