import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createClient } from "@supabase/supabase-js";
import { actor, env, rpc, setup } from "./v4-fixtures.mjs";
import { dayOffset, localToday } from "./shift-fixtures.mjs";
import { sql, sqlLiteral } from "../../scripts/test-environment.mjs";
import { fixturePassword } from "../../scripts/test-constants.mjs";

async function worker(patient) {
  const service = createClient(env.url, env.serviceKey, { auth: { persistSession: false } });
  const email = `schedule-${randomUUID()}@example.invalid`;
  const created = await service.auth.admin.createUser({ email, password: fixturePassword, email_confirm: true });
  assert.ifError(created.error);
  const id = created.data.user.id;
  sql(`insert into public.profiles(id,full_name,role,status) values(${sqlLiteral(id)},'Profissional fictício de escalas','professional','active') on conflict(id) do nothing;
  insert into public.care_recipient_memberships(care_recipient_id,user_id,role) values(${sqlLiteral(patient)},${sqlLiteral(id)},'professional');`);
  const client = createClient(env.url, env.anonKey, { auth: { persistSession: false } });
  assert.ifError((await client.auth.signInWithPassword({ email, password: fixturePassword })).error);
  await rpc(client, "select_active_context", { p_patient: patient });
  return { id, client };
}
const command = (client, patient, action, body, version = null, key = randomUUID()) => rpc(client, "schedule_command", { p_patient: patient, p_action: action, p_body: body, p_version: version, p_key: key });
test("schedules persist proposals, overnight recurrences, revisions, scope and cross-patient exclusion", async () => {
  const { patient, admin } = await setup(), pro = await worker(patient);
  const type = await command(admin, patient, "type", { name: "Noturno", startsLocal: "19:00", durationMinutes: 720 });
  // Keep the proposal in the future without bypassing the retroactive-reason guard.
  const anchorDate = dayOffset(localToday(), 2), nextDate = dayOffset(anchorDate, 1), secondDate = dayOffset(anchorDate, 2);
  const range = { p_patient: patient, p_from: dayOffset(anchorDate, -1), p_until: dayOffset(anchorDate, 6) };
  const body = { professionalId: pro.id, shiftTypeId: type.id, timezone: "America/Sao_Paulo", recurrence: "cycle", workHours: 12, restHours: 36, weekdays: [], anchorDate, validUntil: dayOffset(anchorDate, 4), notes: "12x36 fictício" };
  const retroactive = await pro.client.rpc("schedule_command", { p_patient: patient, p_action: "series", p_key: randomUUID(), p_body: { ...body, anchorDate: dayOffset(anchorDate, -3), recurrence: "once" } });
  assert.equal(retroactive.error?.message, "retroactive reason required");
  const key = randomUUID();
  const proposed = await command(pro.client, patient, "series", body, null, key);
  assert.equal(proposed.status, "proposed");
  assert.equal((await command(pro.client, patient, "series", body, null, key)).id, proposed.id);
  assert.ok((await pro.client.rpc("schedule_command", { p_patient: patient, p_action: "approve", p_body: { id: proposed.id }, p_key: randomUUID(), p_version: 1 })).error);
  await command(admin, patient, "approve", { id: proposed.id }, 1);
  let workspace = await rpc(pro.client, "schedule_workspace", range);
  assert.equal(workspace.shifts.length, 3);
  assert.equal(workspace.shifts[0].starts_at, `${anchorDate}T22:00:00+00:00`);
  assert.equal(workspace.shifts[0].ends_at, `${nextDate}T10:00:00+00:00`);
  assert.equal(workspace.shifts[1].starts_at, `${secondDate}T22:00:00+00:00`);
  const shift = workspace.shifts[0];
  const change = await command(pro.client, patient, "propose_change", { id: shift.id, reason: "Correção pontual fictícia", startsAt: `${anchorDate}T23:00:00Z`, endsAt: `${nextDate}T11:00:00Z` }, shift.version);
  await command(admin, patient, "decide_change", { id: change.id, approve: true, reason: "Ajuste autorizado" }, change.version);
  workspace = await rpc(pro.client, "schedule_workspace", range);
  assert.equal(workspace.shifts[0].is_exception, true);
  assert.equal(workspace.changes.length, 0);
  assert.ok((await pro.client.from("scheduled_shifts").update({ status: "cancelled" }).eq("id", shift.id)).error);
  const reader = await actor("reader", patient);
  assert.ok((await reader.rpc("schedule_command", { p_patient: patient, p_action: "series", p_body: body, p_key: randomUUID() })).error);
  const outsider = await actor("global");
  assert.ok((await outsider.rpc("schedule_workspace", range)).error);
  const other = await setup();
  sql(`insert into public.care_recipient_memberships(care_recipient_id,user_id,role) values(${sqlLiteral(other.patient)},${sqlLiteral(pro.id)},'professional');`);
  const otherType = await command(other.admin, other.patient, "type", { name: "Noturno", startsLocal: "19:00", durationMinutes: 720 });
  const conflict = await other.admin.rpc("schedule_command", { p_patient: other.patient, p_action: "series", p_key: randomUUID(), p_body: { ...body, shiftTypeId: otherType.id, recurrence: "once" } });
  assert.equal(conflict.error?.code, "23P01");
  assert.equal(conflict.error.message, "schedule overlap");
  assert.equal((await pro.client.from("scheduled_shifts").select("id").eq("care_recipient_id", other.patient)).data.length, 0);
  await actor("adminA", patient);
  const end = await command(admin, patient, "end_series", { id: proposed.id, fromDate: secondDate, reason: "Encerrar programação futura" }, 2);
  assert.equal(end.version, 3);
  const rows = await rpc(admin, "schedule_workspace", range);
  assert.equal(rows.shifts.filter(s => s.status === "published").length, 1);
  assert.ok(rows.events.length >= 4);
});
